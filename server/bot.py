SHARED_SYSTEM_APPENDIX = """

— Memory & onboarding —
You will receive a memory brief at the start of each conversation, wrapped in a
"[Memory brief — internal context, do not read aloud or quote]" block.
- If the brief says no prior conversations exist, this is the first time you
  meet this user. Get their name when it feels natural — once, gently, and
  only the name. Do not ask for age, gender, family, or work; let those
  surface on their own as the user chooses to share.
- If the brief contains a profile and recent sessions, treat the user as
  someone you know. Don't recite their facts back at them; just speak like
  someone who remembers.
- Never read the memory brief aloud, paraphrase it verbatim, or quote it.
"""

# Map persona `lang` codes to language names for the output-language directive.
_LANG_NAMES = {"en": "English", "fr": "French"}


def _language_directive(lang: str) -> str:
    """Pin the persona's spoken language so prior-session memory (which may be in
    another language) or a user speaking something else can't flip it. `lang`
    only steered STT/TTS before; the LLM had no language instruction at all."""
    name = _LANG_NAMES.get(lang.split("-")[0].lower(), "English")
    return (
        f"\n\n— Language —\n"
        f"Always speak {name}. Every response must be in {name}, regardless of the "
        f"language of the memory brief, earlier context, or anything the user says. "
        f"The memory brief is internal notes that may be in another language — never "
        f"mirror its language. If the user speaks another language, gently continue "
        f"in {name}."
    )


# Spoken when STT stalls (no final transcript). Keyed by persona language so a
# non-English session doesn't break into English on a recovery prompt.
_STT_RECOVERY_MESSAGES = {
    "en": "Sorry, I didn't catch that — could you say it again?",
    "fr": "Pardon, je n'ai pas saisi — pouvez-vous répéter ?",
}


def _stt_recovery_message(lang: str) -> str:
    return _STT_RECOVERY_MESSAGES.get(
        lang.split("-")[0].lower(), _STT_RECOVERY_MESSAGES["en"]
    )


def build_llm(persona: Persona):
    """Assemble the shared system instruction, then dispatch to the LLM provider
    factory registered for `persona.llm_provider` (`openai`/`anthropic`/`groq`)."""
    lang = (persona.lang or "en").lower()
    system_instruction = (
        persona.system_prompt
        + SHARED_SYSTEM_APPENDIX
        + _language_directive(lang)
    )
    factory = providers.LLM_FACTORIES.get(persona.llm_provider)
    if factory is None:
        raise ValueError(f"Unknown LLM provider in persona: {persona.llm_provider!r}")
    return factory(persona, system_instruction)


async def prewarm_llm(llm) -> None:
    """Open the LLM's HTTP connection during the idle gap before the caller
    joins, so the first real turn (the intro) doesn't pay cold-start cost.

    The first OpenAI/Anthropic/Groq request of a session eats DNS+TLS+HTTP
    setup (~3.4s TTFB observed); later turns reuse the pooled connection and are
    fast. We fire a cheap ``models.list()`` on the service's own ``_client`` —
    the same pool the pipeline reuses for completions — and discard it. It never
    touches the pipeline, so nothing is spoken or recorded.

    Best-effort: any failure (offline, auth, SDK change) is swallowed so a
    session is never broken — worst case is the pre-existing cold start.
    """
    client = getattr(llm, "_client", None)
    if client is None:
        return
    try:
        await client.models.list()
        logger.info("LLM connection pre-warmed")
    except Exception as e:
        logger.debug(f"LLM prewarm skipped: {e}")


def build_tts(persona: Persona):
    """Dispatch to the TTS provider factory registered for `persona.tts_provider`
    (`cartesia`/`deepgram`/`gradium`). The seam is here so ElevenLabs/Hume can
    slot in later (see notes.md intended stack)."""
    lang = (persona.lang or "en").lower()
    # SENTENCE (default) buffers to sentence boundaries; TOKEN streams tokens
    # for lower first-word latency. persona guarantees one of these two names.
    agg_mode = TextAggregationMode[persona.text_aggregation_mode]
    factory = providers.TTS_FACTORIES.get(persona.tts_provider)
    if factory is None:
        raise ValueError(f"Unknown TTS provider in persona: {persona.tts_provider!r}")
    return factory(persona, lang, agg_mode)


async def run_bot(
    transport: BaseTransport,
    agent_name: str,
    pool: asyncpg.Pool,
    user_id: str | None = None,
):
    """Main bot logic."""
    persona = load_persona(agent_name)
    logger.info(f"Starting bot with persona: {persona.name}")

    # Speech-to-Text service — pick a model that supports the persona language.
    # nova-3 is English-only; for non-English use nova-2 (override via stt.model).
    lang = (persona.lang or "en").lower()
    stt_model = persona.stt_model or ("nova-3" if lang.startswith("en") else "nova-2")
    # StallGuardedDeepgramSTTService adds a watchdog on top of the base service:
    # if a turn ends with no final transcript (a silently half-open Deepgram
    # socket — the failure pipecat does NOT auto-recover; see deepgram_stt.py),
    # it forces a reconnect so the next turn lands on a healthy connection and
    # speaks `recovery_message` so the dead air is audible.
    stt = StallGuardedDeepgramSTTService(
        api_key=get_settings().deepgram_api_key,
        settings=DeepgramSTTService.Settings(
            model=stt_model,
            language=lang,
            profanity_filter=False,
        ),
        recovery_message=_stt_recovery_message(lang),
    )
    logger.info(f"STT: {persona.stt_provider} model={stt_model} language={lang}")

    # Text-to-Speech service (provider routed from persona.tts_provider)
    tts = build_tts(persona)
    logger.info(f"TTS: {persona.tts_provider} voice={persona.voice_id} language={lang}")


    # LLM service (provider routed from persona.llm_provider)
    llm = build_llm(persona)
    logger.info(f"LLM: {persona.llm_provider}:{persona.llm_model}")

    # Warm the LLM connection now, while the caller is still connecting, so the
    # intro turn isn't the cold first request. Fire-and-forget; keep a reference
    # so the task isn't garbage-collected mid-flight.
    prewarm_task = asyncio.create_task(prewarm_llm(llm))



    context = LLMContext()
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(
            vad_analyzer=SileroVADAnalyzer(),    ),
    )


    # Pipeline - assembled from reusable components
    pipeline = Pipeline([
        transport.input(),
        stt,
        user_aggregator,
        llm,
        tts,
        transport.output(),
        assistant_aggregator,
    ])


    # Recording (session row, transcript, metrics) is always on for
    # observability. Cross-session memory is decoupled: persona.memory == False
    # → blank slate, so we neither retrieve a past-session brief nor write user
    # memory at close (update_memory=False), but the session is still recorded.
    recorder = SessionRecorder(pool, persona, user_id=user_id, update_memory=persona.memory)
    await recorder.start()
    logger.info(f"Recording session {recorder.session_id} to Supabase")
    if persona.memory:
        memory_brief = await load_memory_brief(pool, user_id)
        if memory_brief:
            logger.info(f"Loaded memory brief ({len(memory_brief)} chars) for user {user_id}")
    else:
        memory_brief = None
        logger.info("Memory off for this persona — blank slate (recorded, no cross-session memory)")

    transcript_observer = TranscriptObserver(recorder)
    task = PipelineTask(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[transcript_observer],
    )

    kicked_off = False

    async def kickoff(source: str):
        nonlocal kicked_off
        if kicked_off:
            return
        kicked_off = True
        logger.info(f"Kicking off conversation via {source}")
        if memory_brief:
            context.add_message({"role": "user", "content": memory_brief})
        for msg in persona.opening_messages:
            context.add_message(msg)
            recorder.record_message(role=msg.get("role", "system"), text=msg.get("content", ""))
        await task.queue_frames([LLMRunFrame()])

    # RTVI-aware clients (e.g. Pipecat React SDK) — keep for forward-compat.
    @task.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        await kickoff("rtvi:on_client_ready")

    # Daily transport: fires when the first non-bot participant joins.
    # This is the one that triggers for our daily-js browser client.
    @transport.event_handler("on_first_participant_joined")
    async def on_first_participant_joined(transport, participant):
        logger.info(f"First participant joined: {participant.get('id', '?')}")
        await kickoff("daily:on_first_participant_joined")

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        # Synthesize a TTS char estimate if the provider never reported one
        # (e.g. Deepgram WS). Must run before close() reads the totals.
        transcript_observer.finalize_tts_chars()
        await recorder.close()
        await task.cancel()



    runner = PipelineRunner(handle_sigint=False)

    await runner.run(task)


async def run_daily_bot(
    room_url: str,
    token: str,
    agent_name: str,
    pool: asyncpg.Pool,
    user_id: str | None = None,
):
    """Join a Daily room as the bot. Used by server.py /start-session."""
    transport = DailyTransport(
        room_url,
        token,
        "Inigo",
        params=DailyParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
    )
    await run_bot(transport, agent_name, pool, user_id=user_id)


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""

    transport = None

    match runner_args:
        case DailyRunnerArguments():
            transport = DailyTransport(
                runner_args.room_url,
                runner_args.token,
                "Pipecat Bot",
                params=DailyParams(
                    audio_in_enabled=True,
                    audio_out_enabled=True,
                ),
            )
        case SmallWebRTCRunnerArguments():
            webrtc_connection: SmallWebRTCConnection = runner_args.webrtc_connection

            transport = SmallWebRTCTransport(
                webrtc_connection=webrtc_connection,
                params=TransportParams(
                    audio_in_enabled=True,
                    audio_out_enabled=True,
                ),
            )
        case _:
            logger.error(f"Unsupported runner arguments type: {type(runner_args)}")
            return

    from storage import close_pool, create_pool

    pool = await create_pool()
    try:
        await run_bot(transport, os.getenv("AGENT_NAME", ""), pool)
    finally:
        await close_pool(pool)


if __name__ == "__main__":
    from pipecat.runner.run import main

    main()