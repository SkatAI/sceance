# Spoken when STT stalls (no final transcript). Keyed by persona language so a
# non-English session doesn't break into English on a recovery prompt.
_STT_RECOVERY_MESSAGES = {
    "en": "Sorry, I didn't catch that — could you say it again?",
    "fr": "Pardon, je n'ai pas saisi — pouvez-vous répéter ?",
}


def _stt_recovery_message(lang: str) -> str:
    return _STT_RECOVERY_MESSAGES.get(
        lang.split("-")[0].lower(), _STT_RECOVERY_MESSAGES["en"]
    )


def build_llm(persona: Persona):
    """Select and build the LLM service for the persona's provider. Prompt policy
    (system instruction + language directive) is assembled in `prompting`."""
    system_instruction = prompting.build_system_instruction(persona)
    factory = providers.LLM_FACTORIES.get(persona.llm_provider)
    if factory is None:
        raise ValueError(f"Unknown LLM provider in persona: {persona.llm_provider!r}")
    return factory(persona, system_instruction)


async def prewarm_llm(llm) -> None:
    """Open the LLM's HTTP connection *and* prime the system-prompt cache during
    the idle gap before the caller joins, so the first real turn doesn't pay
    cold-start cost.

    The first OpenAI/Anthropic/Groq request of a session eats DNS+TLS+HTTP
    setup (~3.4s TTFB observed); later turns reuse the pooled connection and are
    fast. We fire a throwaway ``run_inference`` with ``max_tokens=1`` on the same
    pool the pipeline reuses for completions. Unlike a bare ``models.list()``,
    this uses the service's configured system instruction, so for Anthropic
    (``enable_prompt_caching``) it also *writes* the system-prompt cache — the
    first real turn then reads it. It runs out-of-band (no pipeline frames), so
    nothing is spoken or recorded. The throwaway context is enough: the cached
    prefix is the system prompt, independent of these messages.

    Best-effort: any failure (offline, auth, SDK change) is swallowed so a
    session is never broken — worst case is the pre-existing cold start.
    """
    try:
        warm_ctx = LLMContext()
        warm_ctx.add_message({"role": "user", "content": "hi"})
        await llm.run_inference(warm_ctx, max_tokens=1)
        logger.info("LLM connection pre-warmed (cache primed)")
    except Exception as e:
        logger.debug(f"LLM prewarm skipped: {e}")


def build_tts(persona: Persona):
    """Dispatch to the TTS provider factory registered for `persona.tts_provider`
    (`cartesia`/`deepgram`/`gradium`). The seam is here so ElevenLabs/Hume can
    slot in later (see notes.md intended stack)."""
    lang = (persona.lang or "en").lower()
    # SENTENCE (default) buffers to sentence boundaries; TOKEN streams tokens
    # for lower first-word latency. persona guarantees one of these two names.
    agg_mode = TextAggregationMode[persona.text_aggregation_mode]
    factory = providers.TTS_FACTORIES.get(persona.tts_provider)
    if factory is None:
        raise ValueError(f"Unknown TTS provider in persona: {persona.tts_provider!r}")
    return factory(persona, lang, agg_mode)


def build_stt(persona: Persona):
    """Dispatch to the STT provider factory registered for `persona.stt_provider`
    (`deepgram`/`gradium`).

    `stt.provider` used to be parsed and then ignored — STT was always Deepgram.
    It is a real seam now because the gradbot build runs Gradium STT, and a
    latency comparison whose STT vendors differ measures the vendors as much as
    the frameworks.
    """
    lang = (persona.lang or "en").lower()
    factory = providers.STT_FACTORIES.get(persona.stt_provider)
    if factory is None:
        raise ValueError(f"Unknown STT provider in persona: {persona.stt_provider!r}")
    stt = factory(persona, lang, _stt_recovery_message(lang))
    logger.info(f"STT: {persona.stt_provider} language={lang} -> {type(stt).__name__}")
    return stt


def build_context_aggregators():
    """LLM context plus its user/assistant aggregator pair.

    Turn-start / interruption is gated on a real transcript (MinWords) rather
    than raw VAD energy. A contentless VAD blip (a breath/noise ~0.2s after the
    user finished speaking) used to count as the user starting to speak again,
    which cancelled the in-flight LLM turn and left nothing queued — ~13s of dead
    air (online session e6ec5595). VAD still runs (it drives turn-stop timing and
    feeds STT); it just no longer triggers an interruption on its own. Pre-TTS the
    threshold is effectively 1 word, so normal turn-taking is unchanged; min_words
    only applies while the bot is speaking (genuine barge-in). The stop strategy
    is left at its default (stop=None).

    Both knobs are settings, not constants, because the gradbot build has to be
    able to match them for a like-for-like comparison — `min_words` has no gradbot
    equivalent (it barges in on raw VAD), and `stop_secs` must equal gradbot's
    `flush_duration_s` or the two frameworks time "the user stopped talking" from
    different moments.
    """
    settings = get_settings()
    min_words = settings.barge_in_min_words
    if min_words < 2:
        logger.warning(
            f"BARGE_IN_MIN_WORDS={min_words}: barge-in is now raw-VAD driven. This "
            f"re-exposes the contentless-blip dead-air bug — comparison only, not prod."
        )
    context = LLMContext()
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(
            vad_analyzer=SileroVADAnalyzer(
                params=VADParams(stop_secs=settings.vad_stop_secs)
            ),
            user_turn_strategies=UserTurnStrategies(
                start=[MinWordsUserTurnStartStrategy(min_words=min_words)],
            ),
        ),
    )
    return context, user_aggregator, assistant_aggregator


def build_pipeline(transport, stt, llm, tts, user_aggregator, assistant_aggregator):
    """Assemble the cascade pipeline from its reusable components."""
    return Pipeline([
        transport.input(),
        stt,
        user_aggregator,
        llm,
        tts,
        transport.output(),
        assistant_aggregator,
    ])


def create_recorder(pool: asyncpg.Pool, persona: Persona, user_id: str | None):
    """Session recorder. Recording (session row, transcript, metrics) is always on
    for observability; cross-session memory is decoupled — persona.memory == False
    means blank slate, so `update_memory=False` skips writing user memory at close
    while the session is still recorded."""
    return SessionRecorder(pool, persona, user_id=user_id, update_memory=persona.memory)


async def _load_memory_brief(pool, persona: Persona, user_id: str | None) -> str | None:
    """Past-session brief for memory-on personas; None (blank slate) when off."""
    if not persona.memory:
        logger.info("Memory off for this persona — blank slate (recorded, no cross-session memory)")
        return None
    memory_brief = await load_memory_brief(pool, user_id)
    if memory_brief:
        logger.info(f"Loaded memory brief ({len(memory_brief)} chars) for user {user_id}")
    return memory_brief


def make_kickoff(task, context, recorder, persona: Persona, memory_brief: str | None):
    """Return a once-only `kickoff(source)` that seeds the context (memory brief +
    opening messages, the latter also recorded) and produces turn zero.
    Idempotent across triggers (rtvi ready / first participant joined).

    Turn zero is either a fixed line spoken straight to TTS (when the persona
    defines `static_greeting` — no cold LLM inference, so the caller hears the
    agent immediately) or, otherwise, a normal `LLMRunFrame` that lets the LLM
    generate the greeting. Either way the `opening_messages` are kept in context:
    they preserve the user-first message ordering Anthropic requires and give the
    LLM coherent context for the first real turn."""
    state = {"done": False}

    async def kickoff(source: str):
        if state["done"]:
            return
        state["done"] = True
        logger.info(f"Kicking off conversation via {source}")
        if memory_brief:
            context.add_message({"role": "user", "content": memory_brief})
        for msg in persona.opening_messages:
            context.add_message(msg)
            recorder.record_message(role=msg.get("role", "system"), text=msg.get("content", ""))
        if persona.static_greeting:
            # Speak a fixed greeting straight to TTS — no LLM inference, so no
            # cold-start dead air. The TranscriptObserver only records assistant
            # text from LLM frames, so record it manually here (no double-record).
            greeting = persona.static_greeting
            context.add_message({"role": "assistant", "content": greeting})
            recorder.record_message(role="assistant", text=greeting)
            await task.queue_frames([TTSSpeakFrame(text=greeting)])
        else:
            await task.queue_frames([LLMRunFrame()])

    return kickoff


def register_transport_handlers(transport, task, recorder, transcript_observer, kickoff):
    """Wire the kickoff triggers and the disconnect teardown onto the transport/task."""

    # RTVI-aware clients (e.g. Pipecat React SDK) — keep for forward-compat.
    @task.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        await kickoff("rtvi:on_client_ready")

    # Daily transport: fires when the first non-bot participant joins.
    # This is the one that triggers for our daily-js browser client.
    @transport.event_handler("on_first_participant_joined")
    async def on_first_participant_joined(transport, participant):
        logger.info(f"First participant joined: {participant.get('id', '?')}")
        await kickoff("daily:on_first_participant_joined")

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        # Synthesize a TTS char estimate if the provider never reported one
        # (e.g. Deepgram WS). Must run before close() reads the totals.
        transcript_observer.finalize_tts_chars()
        await recorder.close()
        await task.cancel()


async def run_bot(
    transport: BaseTransport,
    agent_name: str,
    pool: asyncpg.Pool,
    user_id: str | None = None,
):
    """Main bot logic — orchestrates the builders into a running pipeline."""
    persona = load_persona(agent_name)
    logger.info(f"Starting bot with persona: {persona.name}")

    stt = build_stt(persona)
    tts = build_tts(persona)
    logger.info(f"TTS: {persona.tts_provider} voice={persona.voice_id}")
    llm = build_llm(persona)
    logger.info(f"LLM: {persona.llm_provider}:{persona.llm_model}")

    # Warm the LLM connection now, while the caller is still connecting, so the
    # intro turn isn't the cold first request. Fire-and-forget; keep a reference
    # so the task isn't garbage-collected mid-flight.
    prewarm_task = asyncio.create_task(prewarm_llm(llm))

    context, user_aggregator, assistant_aggregator = build_context_aggregators()
    pipeline = build_pipeline(transport, stt, llm, tts, user_aggregator, assistant_aggregator)

    recorder = create_recorder(pool, persona, user_id)
    await recorder.start()
    logger.info(f"Recording session {recorder.session_id} to Supabase")
    memory_brief = await _load_memory_brief(pool, persona, user_id)

    transcript_observer = TranscriptObserver(recorder)
    task = PipelineTask(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[transcript_observer],
    )

    kickoff = make_kickoff(task, context, recorder, persona, memory_brief)
    register_transport_handlers(transport, task, recorder, transcript_observer, kickoff)

    runner = PipelineRunner(handle_sigint=False)
    await runner.run(task)


async def run_daily_bot(
    room_url: str,
    token: str,
    agent_name: str,
    pool: asyncpg.Pool,
    user_id: str | None = None,
):
    """Join a Daily room as the bot. Used by server.py /start-session."""
    transport = DailyTransport(
        room_url,
        token,
        "Inigo",
        params=DailyParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
    )
    await run_bot(transport, agent_name, pool, user_id=user_id)